/// The supported subset is Latin-1 Supplement and Latin Extended-A/B.
/// Other scripts retain their spelling unless the native host identifies them.
String _canonicalComponent(String value) {
  final decomposed = _orderCombiningMarks(_decomposeLatin(value.toLowerCase()));

  // Re-decompose after the table-driven compose pass so multi-mark entries
  // have one stable NFD spelling regardless of table iteration order.
  return _orderCombiningMarks(_decomposeLatin(_composeLatin(decomposed)));
}

String _decomposeLatin(String value) {
  final decomposed = StringBuffer();
  for (final rune in value.runes) {
    decomposed.write(_latinDecompositions[rune] ?? String.fromCharCode(rune));
  }

  return decomposed.toString();
}

String _orderCombiningMarks(String value) {
  final ordered = <int>[];
  for (final rune in value.runes) {
    final rank = _combiningClass(rune);
    var at = ordered.length;
    while (rank != 0 &&
        at > 0 &&
        _combiningClass(ordered.elementAtOrNull(at - 1) ?? 0) > rank) {
      at--;
    }
    ordered.insert(at, rune);
  }

  return String.fromCharCodes(ordered);
}

String _composeLatin(String value) {
  var composed = value;
  for (final entry in _latinCompositions.entries) {
    composed = composed.replaceAll(entry.key, entry.value);
  }

  return composed;
}

int _combiningClass(int rune) => rune >= 0x0300 && rune <= 0x036f
    ? _combiningClasses.elementAtOrNull(rune - 0x0300) ?? 0
    : 0;

